import assert from "node:assert/strict";
import { evaluateHealthcare, healthcareSourceSchema, healthcareReviewSchema, healthcarePolicySchema, healthcareDefaultPolicy, type HealthcareCall } from "./status-list-healthcare";
import { optionSourceConfigSchema } from "./status-list-option-source";
import {statusListActionDraft,statusListActionPayload} from "../client/src/lib/status-list-action-draft";
const failed=(i:number):HealthcareCall=>({id:`${i}`,key:`sip:${i}`,at:i*1000,ended:true,answered:false,talkSeconds:0,failed:true});
const success=(i:number,seconds=3):HealthcareCall=>({...failed(i),answered:true,talkSeconds:seconds,failed:false});
assert.equal(evaluateHealthcare([],new Set()).state,"not_defined");
assert.equal(evaluateHealthcare([failed(1)],new Set()).state,"unreached");
assert.equal(evaluateHealthcare([1,2,3,4].map(failed),new Set()).state,"unreached");
assert.equal(evaluateHealthcare([1,2,3,4,5].map(failed),new Set()).state,"unreachable");
assert.equal(evaluateHealthcare([1,2,3,4,5].map(failed).concat(success(6)),new Set()).state,"reachable");
assert.equal(evaluateHealthcare([success(1),...[2,3,4,5,6].map(failed)],new Set()).state,"reachable");
assert.equal(evaluateHealthcare([success(1),failed(2)],new Set()).failedAttempts,1);
assert.equal(evaluateHealthcare([success(1,2.99)],new Set()).state,"unreached");
assert.equal(evaluateHealthcare([success(1)],new Set(["sip:1"])).state,"unreached");
assert.equal(evaluateHealthcare([success(1),success(2)],new Set(["sip:2"])).state,"reachable");
assert.equal(evaluateHealthcare([failed(1),failed(1),failed(1),failed(1),failed(1)],new Set()).state,"unreached");
assert.equal(evaluateHealthcare([{...failed(1),ended:false}],new Set()).state,"not_defined");
assert.equal(evaluateHealthcare([success(1)],new Set(),{state:"not_working",at:2000}).state,"not_working");
assert.equal(evaluateHealthcare([success(3)],new Set(),{state:"not_working",at:2000}).state,"reachable");
const policy=healthcarePolicySchema.parse({failedAttempts:2,minTalkSeconds:10});
assert.equal(evaluateHealthcare([failed(1),failed(2)],new Set(),{},policy).state,"unreachable");
assert.equal(evaluateHealthcare([success(1,3)],new Set(),{},policy).state,"unreached");
assert.equal(evaluateHealthcare([success(1,10)],new Set(),{},policy).state,"reachable");
const disabled=healthcarePolicySchema.parse({enabled:{unreachable:false}});
assert.equal(evaluateHealthcare([1,2,3,4,5].map(failed),new Set(),{},disabled,"unreached").state,"unreached");
assert.equal(evaluateHealthcare([1,2,3,4,5].map(failed),new Set(),{},disabled,"unreached").held,true);
const allOff=healthcarePolicySchema.parse({enabled:Object.fromEntries(Object.keys(healthcareDefaultPolicy.enabled).map(s=>[s,false]))});
assert.equal(evaluateHealthcare([failed(1)],new Set(),{},allOff).active,false);
assert.equal(evaluateHealthcare([failed(1),failed(2)],new Set(),{},healthcareDefaultPolicy,undefined,2000).failedAttempts,0);
assert.equal(evaluateHealthcare([failed(1),failed(3)],new Set(),{},healthcareDefaultPolicy,undefined,2000).failedAttempts,1);
assert.equal(evaluateHealthcare([failed(1),failed(2)],new Set(),{state:"long_term_absent",at:3000}).failedAttempts,2);
assert.equal(evaluateHealthcare([failed(1),success(2)],new Set()).failedAttempts,0,"doctor or personnel connection resets");
assert.equal(evaluateHealthcare([failed(1),success(2)],new Set(["sip:2"])).failedAttempts,2,"voicemail never resets");
for(const raw of [{failedAttempts:0},{failedAttempts:1.5},{failedAttempts:101},{minTalkSeconds:0},{minTalkSeconds:3601},{failedAttempts:"5"},{enabled:{invalid:true}}]) {
  assert.equal(healthcarePolicySchema.safeParse(raw).success,false);
}
assert.deepEqual(healthcarePolicySchema.parse({}),healthcareDefaultPolicy);
const mapping={not_defined:"0",unreached:"1",unreachable:"2",reachable:"3",wrong_number:"4",not_working:"5",long_term_absent:"6"};
assert.ok(healthcareSourceSchema.safeParse({source:"healthcare_reachability",hidden:true,mapping}).success);
assert.ok(optionSourceConfigSchema.safeParse({source:"healthcare_reachability",hidden:true,mapping}).success);
assert.ok(!optionSourceConfigSchema.safeParse({source:"healthcare_reachability",hidden:true,mapping:{...mapping,unreachable:"1"}}).success);
assert.ok(healthcareReviewSchema.safeParse({state:"unreachable",substatus:"doctor_left",proposedContact:"",expectedFingerprint:"a".repeat(64)}).success);
assert.equal(statusListActionDraft(undefined,"set_callback").executionPolicy,"automatic");
const oldAction={actionType:"set_callback",callbackOffsetDays:6};
const draft=statusListActionDraft(oldAction);
assert.equal(draft.executionPolicy,"inherit");
assert.equal(statusListActionPayload({...draft,executionPolicy:"review"},oldAction).executionPolicy,"review");
console.log("Healthcare policy and action execution: defaults, configurable limits, disabled states, counter boundaries and execution checks passed");
