import assert from "node:assert/strict";
import { outlineHidden, outlineCategory, outlinePhase, statusListOutline, type OutlineItem } from "./status-list-outline";
import { emptyStatusListOrganization, remapStatusListOrganization } from "@shared/status-list-organization";
const row = (id: string, parentId: string | null, tab?: string | null): OutlineItem => ({ id, parentId, tab, label: id, stepId: `CODE-${id}`, itemType: "step", questions: [] });
const items = [row("a", null, "acquisition"), row("r", null, "retention"), row("c", null, "contract"), row("shared", null), row("child", "a"), row("override", "a", "retention"), { ...row("quick", null), itemType: "option" }];
items[0].questions.push({ id: "q", questionText: "Question", isHidden: false });
items[4].isHidden = true;
const ids = (phase: string) => statusListOutline(items, phase, "", "", emptyStatusListOrganization);
assert.deepEqual([...ids("acquisition").visibleItems].sort(), ["a", "child"]);
assert.deepEqual([...ids("retention").visibleItems].sort(), ["a", "override", "r"]);
assert.deepEqual([...ids("retention").matchingItems].sort(), ["override", "r"]);
assert.deepEqual([...ids("contract").visibleItems], ["c"]);
assert.deepEqual([...ids("shared").matchingItems], ["shared"]);
assert.deepEqual([...ids("quick").visibleItems], ["quick"]);
assert.equal(ids("all").visibleItems.size, items.length);
assert.equal(ids("retention").visibleQuestions.has("q"), false);
assert.equal(ids("acquisition").visibleQuestions.has("q"), true);
assert.equal(ids("retention").matchingItems.has("a"), false, "Wrong-phase ancestors are navigation context only");
assert.equal(ids("acquisition").visibleItems.has("override"), false, "Explicit child phase overrides parent");
items[4].questions.push({ id: "hidden-q", questionText: "Inherited hidden" });
items[0].questions.push({ id: "own-hidden-q", questionText: "Hidden question", isHidden: true });
const visibility = (value: "visible" | "hidden") => statusListOutline(items, "acquisition", "", "", emptyStatusListOrganization, value);
assert.deepEqual([...visibility("hidden").matchingItems], ["child"]);
assert.equal(visibility("hidden").visibleQuestions.has("q"), false);
assert.equal(visibility("hidden").visibleQuestions.has("hidden-q"), true);
assert.equal(visibility("hidden").visibleQuestions.has("own-hidden-q"), true);
assert.equal(visibility("visible").visibleQuestions.has("q"), true);
assert.equal(visibility("visible").visibleQuestions.has("hidden-q"), false);
assert.equal(visibility("visible").visibleQuestions.has("own-hidden-q"), false);
assert.equal(outlineHidden(items[4], items), true);
assert.equal(outlineHidden(items[0], items), false);
const categoryId = "cf2f7c9c-fcf5-4c18-b753-d36e079a9e38";
const organization = { categories: [{ id: categoryId, name: "Settings only" }], assignments: { a: categoryId } };
assert.equal(outlineCategory("q", items[0], items, organization), categoryId);
assert.deepEqual([...statusListOutline(items, "all", categoryId, "", organization).visibleItems].sort(), ["a", "child", "override"]);
assert.deepEqual([...statusListOutline(items, "all", "", "Question", organization).visibleQuestions], ["q", "own-hidden-q"]);
assert.deepEqual([...statusListOutline(items, "all", "", "CODE-child", organization).visibleItems].sort(), ["a", "child"]);
assert.equal(statusListOutline(items, "all", "", "no match", organization).visibleItems.size, 0);
const copy = remapStatusListOrganization(organization, new Map([["a", "new-a"]]), () => "dc76d805-a55c-4387-9de4-14fa9536e331");
assert.notEqual(copy.categories[0].id, categoryId);
assert.equal(copy.assignments["new-a"], copy.categories[0].id);
assert.equal(copy.assignments.a, undefined);
const legacyMpn = ["acquisition_contacted", "contract_signed", "retention_active"].map((key, index) => ({
  id: `legacy-${index}`, parentId: null, label: `MPN ${key}`, stepId: `MPN-${index}`, tab: null,
  canonicalClinicStatusKey: key, questions: [],
}));
for (const phase of ["acquisition", "contract", "retention"]) assert.equal(statusListOutline(legacyMpn, phase, "", "", emptyStatusListOrganization).matchingItems.size, 0);
assert.equal(statusListOutline(legacyMpn, "shared", "", "", emptyStatusListOrganization).matchingItems.size, 3);
assert.equal(outlinePhase(legacyMpn[0], legacyMpn), null, "Canonical cooperation state cannot silently place imported MPN questions");
assert.equal(outlinePhase(items.find(item => item.id === "child")!, items), "acquisition");
assert.equal(outlinePhase(items.find(item => item.id === "override")!, items), "retention");
console.log("Status List outline phase, context, visibility, search and legacy remapping checks passed");
