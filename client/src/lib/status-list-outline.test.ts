import assert from "node:assert/strict";
import { outlineHidden, outlineCategory, statusListOutline, type OutlineItem } from "./status-list-outline";
import { emptyStatusListOrganization, remapStatusListOrganization } from "@shared/status-list-organization";
const row = (id: string, parentId: string | null, tab?: string | null): OutlineItem => ({ id, parentId, tab, label: id, stepId: `CODE-${id}`, itemType: "step", questions: [] });
const items = [row("a", null, "acquisition"), row("r", null, "retention"), row("c", null, "contract"), row("shared", null), row("child", "a"), row("override", "a", "retention"), { ...row("quick", null), itemType: "option" }];
items[0].questions.push({ id: "q", questionText: "Question", isHidden: false });
items[4].isHidden = true;
const ids = (phase: string) => statusListOutline(items, phase, "", "", emptyStatusListOrganization);
assert.deepEqual([...ids("acquisition").visibleItems].sort(), ["a", "child", "shared"]);
assert.deepEqual([...ids("retention").visibleItems].sort(), ["a", "override", "r", "shared"]);
assert.deepEqual([...ids("contract").visibleItems], ["c", "shared"]);
assert.deepEqual([...ids("quick").visibleItems], ["quick"]);
assert.equal(ids("all").visibleItems.size, items.length);
assert.equal(ids("retention").visibleQuestions.has("q"), false);
assert.equal(ids("acquisition").visibleQuestions.has("q"), true);
assert.equal(outlineHidden(items[4], items), true);
assert.equal(outlineHidden(items[0], items), false);
const categoryId = "cf2f7c9c-fcf5-4c18-b753-d36e079a9e38";
const organization = { categories: [{ id: categoryId, name: "Settings only" }], assignments: { a: categoryId } };
assert.equal(outlineCategory("q", items[0], items, organization), categoryId);
assert.deepEqual([...statusListOutline(items, "all", categoryId, "", organization).visibleItems].sort(), ["a", "child", "override"]);
assert.deepEqual([...statusListOutline(items, "all", "", "Question", organization).visibleQuestions], ["q"]);
assert.deepEqual([...statusListOutline(items, "all", "", "CODE-child", organization).visibleItems].sort(), ["a", "child"]);
assert.equal(statusListOutline(items, "all", "", "no match", organization).visibleItems.size, 0);
const copy = remapStatusListOrganization(organization, new Map([["a", "new-a"]]), () => "dc76d805-a55c-4387-9de4-14fa9536e331");
assert.notEqual(copy.categories[0].id, categoryId);
assert.equal(copy.assignments["new-a"], copy.categories[0].id);
assert.equal(copy.assignments.a, undefined);
console.log("Status List outline: 17 checks passed");
